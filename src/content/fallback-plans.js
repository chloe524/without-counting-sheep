export function fallbackPlan({ track, week, safety, pattern }) {
  const ctx = { ...safety, pattern };
  if (track === 'short') return { ...SHORT[week](ctx), sources: [] };
  const { title, summary, focus, tasks } = LONG[week](ctx);
  return {
    title,
    summary,
    days: focus.map((f, i) => ({ focus: f, tasks: [tasks[i]] })),
    sources: [],
  };
}
